// Writes the game data the in-game addon needs (recipes, reagents, the items they use,
// vendor reagents, gathered items, profession names) as a Lua file:
//   addon/FlipExport/Data/GameData.lua
// from the site's game data in public/data (run `npm run data` first).
// Usage: node scripts/build-addon-data.mjs [dataDir] [outFile]

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DATA = process.argv[2] ?? join(here, '..', 'public', 'data');
const OUT = process.argv[3] ?? join(here, '..', '..', 'addon', 'FlipExport', 'Data', 'GameData.lua');

const json = async (f) => JSON.parse(await readFile(join(DATA, f), 'utf8'));

/** The site's lists, read from its TypeScript sources (plain literals). */
export async function siteLists() {
  const vendorTs = await readFile(join(here, '..', 'src', 'vendor.ts'), 'utf8');
  const vendorBody = vendorTs.slice(vendorTs.indexOf('VENDOR_REAGENTS'), vendorTs.indexOf('];'));
  const vendor = [...vendorBody.matchAll(/^\s*(\d+),/gm)].map((m) => Number(m[1]));
  const gatherTs = await readFile(join(here, '..', 'src', 'gather.ts'), 'utf8');
  const gather = {};
  const body = gatherTs.slice(gatherTs.indexOf('const GATHERS'));
  for (const block of body.matchAll(/(\w+): \[([\s\S]*?)\n  \],/g)) {
    gather[block[1]] = [...block[2].matchAll(/\[(\d+), '(?:[^'\\]|\\.)*', (\d+)\]/g)].map((m) => [Number(m[1]), Number(m[2])]);
  }
  if (vendor.length < 5 || Object.keys(gather).length < 2) throw new Error('could not read the vendor or gather lists from the site sources');
  return { vendor, gather };
}

const lua = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;

/** Lua source for the data; statements chunked into functions so no function hits Lua's constant limit. */
export function toLua({ meta, items, recipes, skills, vendor, gather }) {
  const used = new Set([...vendor, ...Object.values(gather).flat().map(([id]) => id)]);
  for (const r of recipes) {
    used.add(r[5]);
    for (const [id] of r[7]) used.add(id);
    if (r[9]) used.add(r[9]);
  }
  const lines = [];
  const chunk = (stmts) => {
    for (let i = 0; i < stmts.length; i += 400) lines.push('do', ...stmts.slice(i, i + 400), 'end');
  };
  lines.push(
    '-- Generated by web/scripts/build-addon-data.mjs from the WoW Forever game tables (wago.tools). Do not edit.',
    'local _, ns = ...',
    'local D = { items = {}, recipes = {}, skills = {}, vendorReagents = {}, gather = {} }',
    'ns.GameData = D',
    `D.build = ${lua(meta.build)}`,
    'local I, R = D.items, D.recipes',
  );
  for (const [id, name] of Object.entries(skills)) lines.push(`D.skills[${id}] = ${lua(name)}`);
  lines.push(`D.vendorReagents = { ${vendor.join(', ')} }`);
  for (const [prof, list] of Object.entries(gather)) lines.push(`D.gather[${lua(prof)}] = { ${list.map(([id, s]) => `{ ${id}, ${s} }`).join(', ')} }`);
  // items[id] = { name, quality, vendor sell price, vendor buy price, vendor stack, max stack }
  const itemStmts = [];
  for (const [id, name, quality, sell, buy, vstack, stack] of items) {
    if (used.has(id)) itemStmts.push(`I[${id}] = { ${lua(name)}, ${quality || 0}, ${sell || 0}, ${buy || 0}, ${vstack || 1}, ${stack || 1} }`);
  }
  chunk(itemStmts);
  // recipes: { spell, name, skill, yellow, grey, output, quantity, { reagent, count, ... }, learn level from the recipe item, recipe item }
  chunk(
    recipes.map(([spell, name, skill, yellow, grey, out, qty, reagents, learnMin, teachItem, teachRank]) => {
      const learn = (teachItem && teachRank) || learnMin || 0;
      return `R[#R + 1] = { ${spell}, ${lua(name)}, ${skill}, ${yellow}, ${grey}, ${out}, ${qty}, { ${reagents.flat().join(', ')} }, ${learn}, ${teachItem || 0} }`;
    }),
  );
  return { text: lines.join('\n') + '\n', items: itemStmts.length, recipes: recipes.length };
}

async function main() {
  const [meta, items, recipes, skills] = await Promise.all(['meta.json', 'items.json', 'recipes.json', 'skills.json'].map(json));
  const lists = await siteLists();
  const out = toLua({ meta, items, recipes, skills, ...lists });
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, out.text);
  console.log(`addon data: ${out.recipes} recipes, ${out.items} items, build ${meta.build} -> ${OUT} (${Math.round(out.text.length / 1024)} KB)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
